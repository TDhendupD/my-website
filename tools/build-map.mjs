// Dev-only: regenerates js/mapdata.js (the world map paths for the quest log map).
//   npm i d3-geo topojson-client topojson-simplify world-atlas us-atlas && node tools/build-map.mjs
// Data: Natural Earth 1:50m land and 1:10m Bhutan (public domain) via world-atlas, US states via us-atlas (US Census).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { geoEquirectangular, geoMercator, geoPath, geoGraticule10, geoInterpolate } from "d3-geo";
import { feature, mesh } from "topojson-client";
import { presimplify, simplify } from "topojson-simplify";
const require = createRequire(import.meta.url);
const world = require("world-atlas/countries-10m.json");
// 1:50m coastlines, thinned a little so the file stays small but still holds up when zoomed in
const landTopo = simplify(presimplify(require("world-atlas/land-50m.json")), 0.012);
const us = require("us-atlas/states-10m.json");
const world50 = simplify(presimplify(require("world-atlas/countries-50m.json")), 0.02);

const SOUTH = -57, NORTH = 84;                        // crop Antarctica and the high Arctic
const W = 1000, H = Math.round((1000 * (NORTH - SOUTH)) / 360); // a plain flat rectangle
const round = (d, digits = 1) => d.replace(/-?\d+\.\d+/g, (n) => String(+(+n).toFixed(digits)));

const land = feature(landTopo, landTopo.objects.land);
const countries = feature(world, world.objects.countries).features;
const bhutan = countries.find((c) => c.properties.name === "Bhutan");
const nc = feature(us, us.objects.states).features.find((s) => s.id === "37");

// Equirectangular: longitude and latitude map straight to x and y, so the map is a true rectangle.
const proj = geoEquirectangular()
  .scale(W / (2 * Math.PI))
  .translate([W / 2, (W / 360) * NORTH])
  .clipExtent([[0, 0], [W, H]]);
const path = geoPath(proj);

const HOME = [89.64, 27.47];      // Thimphu
const DAVIDSON = [-80.85, 35.5];  // Davidson, NC
const route = { type: "LineString", coordinates: Array.from({ length: 60 }, (_, i) => geoInterpolate(HOME, DAVIDSON)(i / 59)) };

// Close-up outlines for the two place cards.
const inset = (f, w = 150, h = 90) => round(geoPath(geoMercator().fitExtent([[6, 6], [w - 6, h - 6]], f))(f));
const insetPoint = (f, pt, w = 150, h = 90) => geoMercator().fitExtent([[6, 6], [w - 6, h - 6]], f)(pt).map((n) => +n.toFixed(1));

const out = {
  width: W, height: H,
  land: round(path(land)),
  // shared borders only (coastlines come from `land`). Natural Earth draws de facto boundaries.
  borders: round(path(mesh(world50, world50.objects.countries, (a, b) => a !== b))),
  graticule: round(path(geoGraticule10()), 0),
  outline: `M0 0H${W}V${H}H0Z`,
  route: round(path(route)),
  bhutan: { shape: round(path(bhutan), 2), point: proj(HOME).map((n) => +n.toFixed(1)), inset: inset(bhutan) },
  nc: { shape: round(path(nc), 2), point: proj(DAVIDSON).map((n) => +n.toFixed(1)), inset: inset(nc), insetPoint: insetPoint(nc, DAVIDSON) },
};
writeFileSync(new URL("../js/mapdata.js", import.meta.url),
  "// Generated by tools/build-map.mjs. Do not edit by hand.\nexport const map = " + JSON.stringify(out) + ";\n");
console.log("land path", out.land.length, "chars; bhutan", out.bhutan.point, "nc", out.nc.point);
